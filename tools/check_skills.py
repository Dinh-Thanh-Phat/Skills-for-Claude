#!/usr/bin/env python3
"""Lint the skill library and regenerate SKILLS.md.

    python tools/check_skills.py            # lint only, exit 1 on problems
    python tools/check_skills.py --catalog  # lint + rewrite SKILLS.md

Checks what breaks a fresh install on someone else's machine:
  - every skills/<name>/ has SKILL.md spelled exactly so (Linux/macOS are case-sensitive)
  - front-matter has name + description
  - no absolute paths into the maintainer's machine (C:/Users/<me>, D:/HK8 ...)
"""
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKILLS = os.path.join(REPO, 'skills')
PERSONAL_PATH = re.compile(r'[A-Za-z]:[\\/]+(Users[\\/]+wi\b|HK8\b)', re.I)

# Catalog groups: first matching prefix wins
GROUPS = [
    ('QA orchestration & test design', ('qa-', 'behavioral-', 'test-case', 'test-generation', 'regression', 'exploratory', 'risk-', 'metamorphic', 'pairwise', 'property-', 'mutation', 'pact-', 'vitest', 'otp-', 'smoke')),
    ('Playwright / web E2E', ('playwright-', 'dom-', 'safe-locator', 'radix', 'cross-browser', 'feature-flag', 'visual-', 'responsive', 'form-', 'data-grid', 'file-upload', 'async-', 'error-state', 'auth-', 'api-', 'browser-', 'network', 'accessibility', 'login-', 'toast', 'wizard', 'realtime', 'timeout', 'synthetic', 'self-healing')),
    ('Mobile (Maestro / Android / iOS)', ('maestro-', 'android-', 'ios-', 'mobile-', 'expo')),
    ('Assertions, stability & debugging', ('fail-loud', 'outcome-', 'cross-module', 'soft-', 'skip-', 'flaky', 'e2e-', 'test-', 'bug-', 'ask-when', 'diagnos', 'state-', 'ui-error', 'expensive-')),
    ('LLM / chatbot / AI evaluation', ('llm-', 'chatbot-', 'deepeval', 'ai-', 'response-', 'qa-generator', 'gdrive-', 'ocr-', 'performance-analyzer', 'rag-', 'prompt-', 'mcp-', 'multimodal', 'strands', 'voice-')),
    ('Data, Sheets & docs', ('gsheet-', 'gapps-', 'file-', 'demo-', 'excel', 'pdf')),
    ('Design & frontend', ('figma-', 'fe-', 'ux-', 'design', 'conversion-', 'microcopy', 'web-vitals')),
    ('Skill & workflow management', ('skill-', 'beads', 'openspec', 'odoo-', 'python-code', 'windows-')),
]


def front_matter(text):
    m = re.match(r'^---\s*\n(.*?)\n---', text, re.S)
    if not m:
        return {}
    out, key = {}, None
    for line in m.group(1).splitlines():
        km = re.match(r'^([A-Za-z_-]+):\s*(.*)$', line)
        if km:
            key, val = km.group(1), km.group(2).strip()
            out[key] = '' if val in ('>', '>-', '|', '|-') else val.strip('"\'')
        elif key and line.startswith((' ', '\t')):
            out[key] = (out[key] + ' ' + line.strip()).strip()
    return out


def group_of(name):
    for title, prefixes in GROUPS:
        # 'xxx-' = prefix match, anything else = substring match
        if any(name.startswith(p) if p.endswith('-') else p in name for p in prefixes):
            return title
    return 'Other'


def main():
    problems, rows = [], []
    for name in sorted(os.listdir(SKILLS)):
        d = os.path.join(SKILLS, name)
        if not os.path.isdir(d):
            problems.append(f'{name}: loose file in skills/ (skills must be folders)')
            continue
        if 'SKILL.md' not in os.listdir(d):
            problems.append(f'{name}: no SKILL.md (exact case)')
            continue
        text = open(os.path.join(d, 'SKILL.md'), encoding='utf-8').read()
        if text.startswith('﻿'):
            problems.append(f'{name}: UTF-8 BOM before front-matter (skill may not load)')
        fm = front_matter(text.lstrip('﻿'))
        if not fm.get('name') or not fm.get('description'):
            problems.append(f'{name}: front-matter needs name + description')
        for root, _, files in os.walk(d):
            for f in files:
                if not f.endswith(('.md', '.py', '.ps1', '.sh', '.cmd', '.json', '.ts', '.js', '.yaml', '.yml')):
                    continue
                p = os.path.join(root, f)
                if 'references' in p and 'gotchas' in f:
                    continue  # incident write-ups quote the original path on purpose
                for i, line in enumerate(open(p, encoding='utf-8', errors='replace'), 1):
                    if PERSONAL_PATH.search(line) and 'maintainer' not in line:
                        problems.append(f'{os.path.relpath(p, REPO)}:{i}: machine-specific path')
        desc = re.split(r'(?<=[.!?])\s|Triggers? on:|Use when', fm.get('description', ''))[0].strip()
        rows.append((group_of(name), name, desc[:160]))

    if '--catalog' in sys.argv:
        out = ['# Skill catalog', '',
               f'{len(rows)} skills. Generated by `python tools/check_skills.py --catalog` — do not edit by hand.',
               'You rarely call these by name: describe the task ("test the login form", "maestro flow flaky")',
               'and Claude loads the matching skill. `qa-router` is the entry point for any testing request.', '']
        for title, _ in GROUPS + [('Other', ())]:
            items = [r for r in rows if r[0] == title]
            if not items:
                continue
            out += [f'## {title} ({len(items)})', '', '| Skill | What it does |', '|---|---|']
            out += [f'| `{n}` | {d.replace("|", "/")} |' for _, n, d in items]
            out.append('')
        open(os.path.join(REPO, 'SKILLS.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
        print(f'SKILLS.md: {len(rows)} skills')

    for p in problems:
        print('  ' + p)
    print(f'{len(rows)} skills checked, {len(problems)} problem(s)')
    sys.exit(1 if problems else 0)


if __name__ == '__main__':
    main()
